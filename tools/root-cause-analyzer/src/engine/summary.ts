import type { Finding, UnavailableFinding } from "../model/types";
import type { AnalysisResult } from "./analyze";

const SEVERITY: Record<Finding["severity"], string> = { critical: "Critical", high: "High", medium: "Medium", low: "Low", info: "Info" };

/** Plain-text (Markdown) incident summary to paste into a ticket. Pure. */
export function buildSummary(result: AnalysisResult, opts: { environment?: string; generatedAt?: Date } = {}): string {
    const { input, timeline } = result;
    const target = timeline.records.find((r) => r.hop === 0);
    const findings = result.findings.filter((f): f is Finding => f.kind === "finding");
    const unavailable = result.findings.filter((f): f is UnavailableFinding => f.kind === "unavailable");
    const lines: string[] = [];

    lines.push(`# Root cause analysis: ${input.table} ${target?.name ? `'${target.name}'` : input.recordId}`, "");
    if (opts.environment) lines.push(`- **Environment:** ${opts.environment}`);
    lines.push(`- **Record:** ${input.table} ${input.recordId}`);
    if (input.column) lines.push(`- **Column of interest:** ${input.column}`);
    lines.push(`- **Window:** ${input.from.toISOString()} → ${input.to.toISOString()}`);
    if (timeline.records.length > 1) {
        lines.push(`- **Related records:** ${timeline.records.filter((r) => r.hop > 0).map((r) => `${r.ref.table} ${r.name ? `'${r.name}'` : r.ref.id} (hop ${r.hop}: ${r.via})`).join("; ")}`);
    }
    lines.push(`- **Activity:** ${timeline.events.length} event(s)`, "");

    lines.push("## Findings", "");
    if (!findings.length) lines.push("No problems found in this window.", "");
    findings.forEach((f, i) => {
        lines.push(`${i + 1}. **[${SEVERITY[f.severity]} · ${f.confidence} confidence] ${f.title}**`);
        lines.push(`   ${f.explanation}`);
        if (f.evidence.length) lines.push(`   Evidence: ${f.evidence.map((e) => e.label).join("; ")}`);
        lines.push("");
    });

    if (unavailable.length) {
        lines.push("## Couldn't check", "");
        unavailable.forEach((u) => lines.push(`- ${u.title}: ${u.reason.replace(/^Unavailable — /, "")}`));
        lines.push("");
    }
    if (timeline.warnings.length) {
        lines.push("## Data notes", "");
        timeline.warnings.forEach((w) => lines.push(`- ${w}`));
        lines.push("");
    }
    lines.push(`_Generated by Root Cause Analyzer (read-only) on ${(opts.generatedAt ?? new Date()).toISOString()}. Stitched links are inferred from timing and identity, not certain._`);
    return lines.join("\n");
}
